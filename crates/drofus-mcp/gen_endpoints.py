#!/usr/bin/env python3
"""Regenerate src/endpoints/table.rs and operations.txt from the dRofus OpenAPI definition.

    curl -s https://api-no.drofus.com/swagger/v1/swagger.json -o swagger.json
    python3 gen_endpoints.py swagger.json

Only GET and OPTIONS operations are read. A write operation is never emitted, whatever the
definition holds.
"""
import json, re, sys

d = json.load(open(sys.argv[1]))
PFX = "/api/{db}/{pr}"
STD = {"$select", "$orderby", "$filter", "$top", "$skip", "db", "pr"}


def pname(p):
    return p["$ref"].split("/")[-1] if "$ref" in p else p["name"]


def rs(s):
    return json.dumps(s, ensure_ascii=False)


def clean(s):
    s = (s or "").replace("\r", "").strip()
    return re.sub(r"\n{3,}", "\n\n", s)


OVERRIDES = {
    ("GET", "/projects"): "drofus_projects_get",
    ("GET", "/users/{id}"): "drofus_users_get",
    ("GET", "/occurrences/{id}/is-member-of-systems"): "drofus_occurrences_member_of_systems",
    ("GET", "/occurrences/{id}/statuses/{statustypeid}"): "drofus_occurrences_status",
    ("GET", "/rooms/{id}/groups/{groupTypeId}"): "drofus_rooms_group",
}


def name_for(method, path):
    if (method, path) in OVERRIDES:
        return OVERRIDES[(method, path)]
    segs = path.strip("/").split("/")
    g = segs[0]
    if method == "OPTIONS":
        return f"drofus_{g}_properties"
    rest = segs[1:]
    if not rest:
        return f"drofus_{g}_list"
    if len(rest) == 1 and rest[0].startswith("{"):
        return f"drofus_{g}_get"
    if rest == ["logs"]:
        return f"drofus_{g}_all_logs"
    if rest[0] == "images" and len(rest) >= 2:
        return f"drofus_{g}_image_meta" if rest[-1] == "meta" else f"drofus_{g}_image"
    if rest[0].startswith("{"):
        return f"drofus_{g}_" + rest[1].replace("-", "_")
    if len(rest) == 1:
        return f"drofus_{g}_{rest[0]}"
    raise SystemExit(f"no name rule for {method} {path}")


rows, ops, names = [], [], set()
for full, item in sorted(d["paths"].items()):
    path = full[len(PFX):]
    for m, kind_m in (("get", "GET"), ("options", "OPTIONS")):
        if m not in item:
            continue
        op = item[m]
        params = op.get("parameters", [])
        names_q = {pname(p) for p in params}
        path_params = [(p["name"], clean(p.get("description"))) for p in params if p.get("in") == "path" and p["name"] not in STD]
        extras = []
        for p in params:
            if "$ref" in p or p.get("in") != "query":
                continue
            t = p["schema"]["type"]
            extras.append((p["name"], clean(p.get("description")), "Int" if t == "integer" else "Bool"))
        has_list = "$top" in names_q
        has_select = "$select" in names_q
        resp = op["responses"].get("200", {}).get("content", {})
        binary = "image/*" in resp
        if kind_m == "OPTIONS":
            kind = "Meta"
        elif binary:
            kind = "Binary"
        elif has_list:
            kind = "List"
        else:
            kind = "Get"
        n = name_for(kind_m, path)
        assert n not in names, n
        names.add(n)
        desc = clean(op.get("summary"))
        extra_desc = clean(op.get("description"))
        rows.append((n, kind, path, path_params, has_select, extras, desc, extra_desc, kind_m))
        ops.append(f"{kind_m} {path}")

out = ["// @generated by gen_endpoints.py from the dRofus OpenAPI definition. Do not edit by hand.\n",
       "use super::{Endpoint, Extra, ExtraTy, Kind};\n\n",
       "pub const ENDPOINTS: &[Endpoint] = &[\n"]
for n, kind, path, pp, sel, extras, desc, xd, mk in rows:
    pps = ", ".join(f"({rs(a)}, {rs(b)})" for a, b in pp)
    ex = ", ".join(f"Extra {{ name: {rs(a)}, description: {rs(b)}, ty: ExtraTy::{c} }}" for a, b, c in extras)
    out.append(
        f"    Endpoint {{ name: {rs(n)}, kind: Kind::{kind}, path: {rs(path)}, path_params: &[{pps}], "
        f"select: {str(sel).lower()}, extras: &[{ex}], summary: {rs(desc)}, notes: {rs(xd)} }},\n")
out.append("];\n")
open("src/endpoints/table.rs", "w").write("".join(out))
open("operations.txt", "w").write("\n".join(sorted(ops)) + "\n")
print(len(rows), "operations")
